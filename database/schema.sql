-- Clean up existing tables (drop child tables first to respect FK constraints)
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
        'AUDIT_LOG', 'CANCELLATIONS', 'BOOKING_TRANSACTIONS', 'RESERVATION_PASSENGERS',
        'RESERVATIONS', 'TRAIN_SEATS', 'TRAIN_SCHEDULES', 'TRAIN_STOPS',
        'ROUTE_CONNECTIONS', 'TRAINS', 'PASSENGERS', 'STATIONS'
    )) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- 1. STATIONS TABLE
CREATE TABLE STATIONS (
    station_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_code    VARCHAR2(10) NOT NULL,
    station_name    VARCHAR2(100) NOT NULL,
    city            VARCHAR2(100) NOT NULL,
    state           VARCHAR2(100) NOT NULL,
    CONSTRAINT UQ_STATION_CODE UNIQUE (station_code)
);

-- 2. PASSENGERS TABLE
CREATE TABLE PASSENGERS (
    passenger_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name         VARCHAR2(100) NOT NULL,
    age               NUMBER(3) NOT NULL,
    gender            VARCHAR2(10),
    phone_number      VARCHAR2(20) NOT NULL,
    email             VARCHAR2(100) NOT NULL,
    registration_date DATE DEFAULT SYSDATE,
    CONSTRAINT CHK_PASSENGER_AGE CHECK (age >= 1 AND age <= 120),
    CONSTRAINT CHK_PASSENGER_GENDER CHECK (gender IN ('Male', 'Female', 'Other'))
);

-- 3. TRAINS TABLE
CREATE TABLE TRAINS (
    train_id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_number        VARCHAR2(10) NOT NULL,
    train_name          VARCHAR2(100) NOT NULL,
    train_type          VARCHAR2(30) DEFAULT 'Superfast',
    source_station_id   NUMBER NOT NULL,
    dest_station_id     NUMBER NOT NULL,
    total_capacity      NUMBER(5) DEFAULT 500,
    status              VARCHAR2(20) DEFAULT 'ACTIVE',
    CONSTRAINT UQ_TRAIN_NUMBER UNIQUE (train_number),
    CONSTRAINT FK_TRAIN_SRC FOREIGN KEY (source_station_id) REFERENCES STATIONS(station_id),
    CONSTRAINT FK_TRAIN_DST FOREIGN KEY (dest_station_id) REFERENCES STATIONS(station_id),
    CONSTRAINT CHK_TRAIN_CAPACITY CHECK (total_capacity > 0),
    CONSTRAINT CHK_TRAIN_STATUS CHECK (status IN ('ACTIVE', 'MAINTENANCE', 'CANCELLED'))
);

-- 4. TRAIN_STOPS TABLE (Intermediate Stops & Timings)
CREATE TABLE TRAIN_STOPS (
    stop_id                 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_id                NUMBER NOT NULL,
    station_id              NUMBER NOT NULL,
    stop_sequence           NUMBER(3) NOT NULL,
    arrival_time            VARCHAR2(10) NOT NULL, -- Format: HH24:MI e.g. '08:30'
    departure_time          VARCHAR2(10) NOT NULL, -- Format: HH24:MI e.g. '08:45'
    distance_from_source_km NUMBER(7, 2) DEFAULT 0 NOT NULL,
    day_offset              NUMBER(2) DEFAULT 0 NOT NULL, -- 0 for same day, 1 for next day
    CONSTRAINT FK_STOP_TRAIN FOREIGN KEY (train_id) REFERENCES TRAINS(train_id) ON DELETE CASCADE,
    CONSTRAINT FK_STOP_STATION FOREIGN KEY (station_id) REFERENCES STATIONS(station_id),
    CONSTRAINT UQ_TRAIN_STOP_SEQ UNIQUE (train_id, stop_sequence),
    CONSTRAINT UQ_TRAIN_STOP_STN UNIQUE (train_id, station_id)
);

-- 5. TRAIN_SCHEDULES TABLE (Schedules by Journey Date)
CREATE TABLE TRAIN_SCHEDULES (
    schedule_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_id            NUMBER NOT NULL,
    departure_date      DATE NOT NULL,
    arrival_date        DATE NOT NULL,
    base_fare           NUMBER(8, 2) DEFAULT 150.00 NOT NULL,
    status              VARCHAR2(20) DEFAULT 'SCHEDULED',
    CONSTRAINT FK_SCHED_TRAIN FOREIGN KEY (train_id) REFERENCES TRAINS(train_id) ON DELETE CASCADE,
    CONSTRAINT UQ_TRAIN_DEP_DATE UNIQUE (train_id, departure_date),
    CONSTRAINT CHK_SCHED_FARE CHECK (base_fare >= 0),
    CONSTRAINT CHK_SCHED_STATUS CHECK (status IN ('SCHEDULED', 'RUNNING', 'COMPLETED', 'CANCELLED'))
);

-- 6. TRAIN_SEATS TABLE (Inventory per Schedule & Travel Class)
CREATE TABLE TRAIN_SEATS (
    seat_inventory_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id         NUMBER NOT NULL,
    seat_class          VARCHAR2(10) NOT NULL,
    total_seats         NUMBER(4) NOT NULL,
    booked_seats        NUMBER(4) DEFAULT 0 NOT NULL,
    available_seats     NUMBER(4) NOT NULL,
    fare_multiplier     NUMBER(4, 2) DEFAULT 1.00 NOT NULL,
    last_updated        TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_SEATS_SCHED FOREIGN KEY (schedule_id) REFERENCES TRAIN_SCHEDULES(schedule_id) ON DELETE CASCADE,
    CONSTRAINT CHK_SEAT_CLASS CHECK (seat_class IN ('1A', '2A', '3A', 'SL')),
    CONSTRAINT CHK_TOTAL_SEATS CHECK (total_seats > 0),
    CONSTRAINT CHK_BOOKED_SEATS CHECK (booked_seats >= 0),
    CONSTRAINT CHK_AVAIL_SEATS CHECK (available_seats >= 0),
    CONSTRAINT CHK_SEAT_SUM CHECK (booked_seats + available_seats = total_seats),
    CONSTRAINT UQ_SCHED_SEAT_CLASS UNIQUE (schedule_id, seat_class)
);

-- 7. RESERVATIONS TABLE
CREATE TABLE RESERVATIONS (
    reservation_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pnr_number          VARCHAR2(20) NOT NULL,
    passenger_id        NUMBER NOT NULL,
    schedule_id         NUMBER NOT NULL,
    from_station_id     NUMBER NOT NULL,
    to_station_id       NUMBER NOT NULL,
    journey_date        DATE NOT NULL,
    seat_class          VARCHAR2(10) NOT NULL,
    passenger_count     NUMBER(3) NOT NULL,
    total_fare          NUMBER(10, 2) NOT NULL,
    booking_status      VARCHAR2(20) DEFAULT 'CONFIRMED',
    booking_time        TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT UQ_RES_PNR UNIQUE (pnr_number),
    CONSTRAINT FK_RES_PASSENGER FOREIGN KEY (passenger_id) REFERENCES PASSENGERS(passenger_id),
    CONSTRAINT FK_RES_SCHEDULE FOREIGN KEY (schedule_id) REFERENCES TRAIN_SCHEDULES(schedule_id),
    CONSTRAINT FK_RES_FROM_STN FOREIGN KEY (from_station_id) REFERENCES STATIONS(station_id),
    CONSTRAINT FK_RES_TO_STN FOREIGN KEY (to_station_id) REFERENCES STATIONS(station_id),
    CONSTRAINT CHK_RES_CLASS CHECK (seat_class IN ('1A', '2A', '3A', 'SL')),
    CONSTRAINT CHK_RES_COUNT CHECK (passenger_count > 0),
    CONSTRAINT CHK_RES_STATUS CHECK (booking_status IN ('CONFIRMED', 'CANCELLED', 'WAITLISTED'))
);

-- 8. RESERVATION_PASSENGERS TABLE
CREATE TABLE RESERVATION_PASSENGERS (
    res_passenger_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id      NUMBER NOT NULL,
    passenger_name      VARCHAR2(100) NOT NULL,
    age                 NUMBER(3) NOT NULL,
    gender              VARCHAR2(10),
    seat_number         VARCHAR2(20) NOT NULL,
    CONSTRAINT FK_RESPASS_RES FOREIGN KEY (reservation_id) REFERENCES RESERVATIONS(reservation_id) ON DELETE CASCADE
);

-- 9. BOOKING_TRANSACTIONS TABLE
CREATE TABLE BOOKING_TRANSACTIONS (
    transaction_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id      NUMBER NOT NULL,
    transaction_ref     VARCHAR2(50) NOT NULL,
    amount              NUMBER(10, 2) NOT NULL,
    payment_method      VARCHAR2(30) DEFAULT 'UPI',
    payment_status      VARCHAR2(20) DEFAULT 'SUCCESS',
    transaction_time    TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT UQ_TX_REF UNIQUE (transaction_ref),
    CONSTRAINT FK_TX_RES FOREIGN KEY (reservation_id) REFERENCES RESERVATIONS(reservation_id) ON DELETE CASCADE,
    CONSTRAINT CHK_TX_METHOD CHECK (payment_method IN ('UPI', 'Credit Card', 'Debit Card', 'Net Banking', 'Cash')),
    CONSTRAINT CHK_TX_STATUS CHECK (payment_status IN ('SUCCESS', 'REFUNDED', 'FAILED'))
);

-- 10. CANCELLATIONS TABLE
CREATE TABLE CANCELLATIONS (
    cancellation_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id      NUMBER NOT NULL,
    cancellation_ref    VARCHAR2(50) NOT NULL,
    cancellation_time   TIMESTAMP DEFAULT SYSTIMESTAMP,
    refund_amount       NUMBER(10, 2) DEFAULT 0 NOT NULL,
    cancellation_charge NUMBER(10, 2) DEFAULT 0 NOT NULL,
    reason              VARCHAR2(255),
    CONSTRAINT UQ_CANCEL_REF UNIQUE (cancellation_ref),
    CONSTRAINT FK_CANCEL_RES FOREIGN KEY (reservation_id) REFERENCES RESERVATIONS(reservation_id)
);

-- 11. ROUTE_CONNECTIONS TABLE (For Dijkstra Graph Algorithm)
CREATE TABLE ROUTE_CONNECTIONS (
    connection_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_station_id     NUMBER NOT NULL,
    to_station_id       NUMBER NOT NULL,
    distance_km         NUMBER(7, 2) NOT NULL,
    travel_time_min     NUMBER(6, 2) NOT NULL,
    is_active           NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_CONN_FROM FOREIGN KEY (from_station_id) REFERENCES STATIONS(station_id),
    CONSTRAINT FK_CONN_TO FOREIGN KEY (to_station_id) REFERENCES STATIONS(station_id),
    CONSTRAINT CHK_CONN_DIST CHECK (distance_km > 0),
    CONSTRAINT CHK_CONN_TIME CHECK (travel_time_min > 0),
    CONSTRAINT CHK_CONN_ACTIVE CHECK (is_active IN (0, 1)),
    CONSTRAINT UQ_ROUTE_PAIR UNIQUE (from_station_id, to_station_id)
);

-- 12. AUDIT_LOG TABLE
CREATE TABLE AUDIT_LOG (
    log_id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name          VARCHAR2(50) NOT NULL,
    operation           VARCHAR2(20) NOT NULL,
    record_id           NUMBER,
    details             VARCHAR2(1000),
    logged_at           TIMESTAMP DEFAULT SYSTIMESTAMP,
    logged_by           VARCHAR2(50) DEFAULT USER
);

-- Performance Indexes
CREATE INDEX IDX_STOPS_TRAIN ON TRAIN_STOPS(train_id);
CREATE INDEX IDX_STOPS_STATION ON TRAIN_STOPS(station_id);
CREATE INDEX IDX_SEATS_SCHED ON TRAIN_SEATS(schedule_id);
CREATE INDEX IDX_RES_PASS ON RESERVATIONS(passenger_id);
CREATE INDEX IDX_RES_SCHED ON RESERVATIONS(schedule_id);
CREATE INDEX IDX_RES_DATE ON RESERVATIONS(journey_date);
CREATE INDEX IDX_CONN_FROM ON ROUTE_CONNECTIONS(from_station_id);
